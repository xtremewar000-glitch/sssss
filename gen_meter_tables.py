"""
gen_meter_tables.py  -  read the engine's meterdb.h and meterdb_v2.h and write meter_tables.py (the part counts and the
position / needle data of every car's meters), which the Meters tab uses to check files the way the engine does and to
draw the meters as the game does.

    python gen_meter_tables.py PATH/TO/src      (the folder with meterdb.h and meterdb_v2.h)
"""
import os
import re
import sys

TYPES = {"METER_FIXED": 0, "METER_SPEED": 1, "METER_REV": 2, "METER_BOOST": 3}


def parse_init(text):
    """a C brace initializer of numbers and METER_ names -> nested lists"""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    toks = re.findall(r"[{}]|-?\d+(?:\.\d+)?|METER_\w+", text)
    pos = 0

    def val():
        nonlocal pos
        t = toks[pos]
        if t == "{":
            pos += 1
            out = []
            while toks[pos] != "}":
                out.append(val())
            pos += 1
            return out
        pos += 1
        if t in TYPES:
            return TYPES[t]
        return float(t) if "." in t else int(t)
    return val()


def table(src, name):
    m = re.search(r"%s\s*\[[^\]]*\]\s*=\s*(\{.*?\n\});" % re.escape(name), src, re.S)
    if not m:
        raise SystemExit("table %s not found" % name)
    return parse_init(m.group(1))


def main(folder):
    legacy = table(open(os.path.join(folder, "meterdb.h")).read(), "METERDB")
    v2 = table(open(os.path.join(folder, "meterdb_v2.h")).read(), "METERDB_V2")
    assert len(legacy) == 55 and len(v2) == 55, (len(legacy), len(v2))
    assert all(len(c) == 5 and len(c[3]) == 2 and len(c[4]) == 2 for c in legacy)
    assert all(len(c) == 2 and len(c[0]) == 6 and len(c[1]) == 6 for c in v2)
    legacy = [(c[0], c[1], c[2], c[3], c[4]) for c in legacy]
    after = open(os.path.join(folder, "meterdb.h")).read().split("by CARDB_PACKS index", 1)[1]
    names = re.findall(r"/\*\s*([A-Za-z0-9]+_[A-Za-z0-9_]+)\s*\*/", after)[:55]
    assert len(names) == 55, len(names)
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "meter_tables.py")
    with open(out, "w") as fh:
        fh.write('"""Generated by gen_meter_tables.py from the engine\'s meterdb.h and meterdb_v2.h: do not edit.\n\n'
                 'LEGACY per car: (arcade car id, hp, gears, [parts in zone 0, 1], [[ [x, y, a0, a1, input, add] ... ] for zone 0, 1]).\nV2 per car: ([parts in each of the 6 zones], [[ [x, y, a0, a1, input, add] ... ] for each zone]).\n'
                 'input: 0 fixed, 1 speed (km/h / 320), 2 rev, 3 boost.  x, y: the sprite centre on the arcade\'s 640 x 480 screen;\n'
                 'the turn in degrees clockwise is a0 + a1 * input; add = drawn added on (glow).\n"""\n')
        fh.write("NAMES = %r\n\nLEGACY = %r\n\nV2 = %r\n" % (names, legacy, v2))
    print("wrote", out, "(%d + %d cars)" % (len(legacy), len(v2)))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
